export const glyphFor = (ch: string): Glyph | null => {
  if (ch === ' ') return {w: 0.36, strokes: []};
  return G[ch.toUpperCase()] ?? null;
};

export const polyLen = (pts: Pt[]) => {
  let l = 0;
  for (let i = 1; i < pts.length; i++) l += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
  return l;
};
