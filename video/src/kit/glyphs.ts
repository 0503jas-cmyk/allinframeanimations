// Single-line "pen" glyphs for stroke-mode InkText. Box: x in em-ish units (cap height = 1), y 0 = top, 1 = baseline.
export type Pt = [number, number];
export type Glyph = {w: number; strokes: Pt[][]};

const arc = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 14): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + (a1 - a0) * (i / n)) * Math.PI) / 180;
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
};

